"""Warp the cleaned CDU map with the QGIS control points and export it for the Flutter app.

Inputs : campus_data/source/cdu_campus_map_clean.png
         campus_data/source/cdu_campus_map.png.points   (QGIS Georeferencer GCPs, EPSG:4326)
Outputs: campus_data/output/cdu_campus_map_3857.tif     (georeferenced, for QGIS checks)
         assets/campus/cdu_campus_map.png               (RGBA image shown in the app)
         lib/data/campus_map_bounds.dart                (corner coordinates of that image)

The image is warped to Web Mercator (EPSG:3857), the projection MapLibre draws in, so the
picture is an exact axis-aligned rectangle and only its four corners are needed in the app.

Run with the QGIS Python (OSGeo4W shell) from the project root:
    python campus_data/scripts/build_app_map.py
"""
import os

from osgeo import gdal, osr

gdal.UseExceptions()
gdal.SetConfigOption("GDAL_PAM_ENABLED", "NO")  # no .aux.xml side files in assets/

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC_PNG = os.path.join(ROOT, "campus_data", "source", "cdu_campus_map_clean.png")
POINTS = os.path.join(ROOT, "campus_data", "source", "cdu_campus_map.png.points")
OUT_DIR = os.path.join(ROOT, "campus_data", "output")
OUT_TIF = os.path.join(OUT_DIR, "cdu_campus_map_3857.tif")
# The flat PDF image is no longer shown in the app (the app draws 3D buildings instead);
# it is kept here for checking alignment and for tracing PDF-only buildings.
APP_PNG = os.path.join(ROOT, "campus_data", "output", "cdu_campus_map_3857.png")
DART = os.path.join(ROOT, "lib", "data", "campus_map_bounds.dart")

PIXEL_SIZE_M = 0.5  # roughly the native resolution of the 400 dpi crop (~0.46 m/px)


def read_gcps(path):
    gcps = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or line.startswith("mapX"):
                continue
            map_x, map_y, src_x, src_y, enabled = line.strip().split(",")[:5]
            if enabled.strip() != "1":
                continue
            # QGIS stores image rows as negative numbers
            gcps.append(gdal.GCP(float(map_x), float(map_y), 0, float(src_x), -float(src_y)))
    return gcps


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(APP_PNG), exist_ok=True)
    os.makedirs(os.path.dirname(DART), exist_ok=True)

    gcps = read_gcps(POINTS)
    wgs84 = osr.SpatialReference()
    wgs84.ImportFromEPSG(4326)
    wgs84.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)  # x = lon, y = lat

    src = gdal.Translate("/vsimem/with_gcps.tif", SRC_PNG, format="GTiff",
                         GCPs=gcps, outputSRS=wgs84)
    gdal.Warp(OUT_TIF, src, dstSRS="EPSG:3857", polynomialOrder=2,
              resampleAlg="cubic", xRes=PIXEL_SIZE_M, yRes=PIXEL_SIZE_M,
              dstAlpha=True, creationOptions=["COMPRESS=DEFLATE"])
    gdal.Unlink("/vsimem/with_gcps.tif")

    out = gdal.Open(OUT_TIF)
    gt = out.GetGeoTransform()
    w, h = out.RasterXSize, out.RasterYSize
    gdal.Translate(APP_PNG, out, format="PNG")

    # Corner coordinates (Web Mercator -> lat/lon)
    merc = osr.SpatialReference()
    merc.ImportFromEPSG(3857)
    to_wgs = osr.CoordinateTransformation(merc, wgs84)
    corners = {
        "topLeft": (gt[0], gt[3]),
        "topRight": (gt[0] + w * gt[1], gt[3]),
        "bottomRight": (gt[0] + w * gt[1], gt[3] + h * gt[5]),
        "bottomLeft": (gt[0], gt[3] + h * gt[5]),
    }
    ll = {k: to_wgs.TransformPoint(x, y)[:2] for k, (x, y) in corners.items()}  # (lon, lat)

    lines = [
        "// GENERATED by campus_data/scripts/build_app_map.py - do not edit by hand.",
        "// Corners of the georeferenced CDU PDF map after georeferencing with",
        f"// {len(gcps)} QGIS control points (Polynomial 2, Web Mercator, {PIXEL_SIZE_M} m/px).",
        "// Source map: CDU Casuarina Campus Map, published August 2024.",
        "import 'package:maplibre_gl/maplibre_gl.dart';",
        "",
        "class CampusMapBounds {",
        "  CampusMapBounds._();",
        "",
        f"  static const int imageWidth = {w};",
        f"  static const int imageHeight = {h};",
        "",
    ]
    for name, (lon, lat) in ll.items():
        lines.append(f"  static const LatLng {name} = LatLng({lat:.7f}, {lon:.7f});")
    lines += [
        "",
        "  static const LatLngQuad quad = LatLngQuad(",
        "    topLeft: topLeft,",
        "    topRight: topRight,",
        "    bottomRight: bottomRight,",
        "    bottomLeft: bottomLeft,",
        "  );",
        "",
        "  static LatLngBounds get bounds => LatLngBounds(",
        "        southwest: LatLng(bottomLeft.latitude, bottomLeft.longitude),",
        "        northeast: LatLng(topRight.latitude, topRight.longitude),",
        "      );",
        "",
        "  static LatLng get centre => LatLng(",
        "        (topLeft.latitude + bottomLeft.latitude) / 2,",
        "        (topLeft.longitude + topRight.longitude) / 2,",
        "      );",
        "",
        "  static bool contains(LatLng p) =>",
        "      p.latitude <= topLeft.latitude &&",
        "      p.latitude >= bottomLeft.latitude &&",
        "      p.longitude >= topLeft.longitude &&",
        "      p.longitude <= topRight.longitude;",
        "}",
        "",
    ]
    with open(DART, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"image {w}x{h}  ->  {APP_PNG}")
    for name, (lon, lat) in ll.items():
        print(f"  {name:12s} lat {lat:.7f}  lon {lon:.7f}")


if __name__ == "__main__":
    main()
